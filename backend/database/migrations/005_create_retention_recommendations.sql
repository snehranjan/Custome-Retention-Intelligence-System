CREATE TABLE IF NOT EXISTS retention_recommendations (
    recommendation_id VARCHAR(50) PRIMARY KEY,
    customer_id VARCHAR(50) NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    prediction_id VARCHAR(50) REFERENCES customer_predictions(prediction_id) ON DELETE SET NULL,
    recommendation_category VARCHAR(100) NOT NULL,
    recommendation_title VARCHAR(255) NOT NULL,
    recommendation_description TEXT NOT NULL,
    evidence TEXT NOT NULL,
    priority VARCHAR(20) NOT NULL CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW')),
    recommendation_status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (recommendation_status IN ('PENDING', 'IN_PROGRESS', 'APPLIED', 'DISMISSED', 'EXPIRED')),
    generated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE retention_recommendations IS 'Stores prioritized, explainable retention interventions generated by the rule engine.';
COMMENT ON COLUMN retention_recommendations.prediction_id IS 'Optional foreign key linking intervention to the originating churn prediction.';
COMMENT ON COLUMN retention_recommendations.evidence IS 'Specific customer signals (spend, return rate, delay friction) justifying the intervention.';
