-- ==============================================================================
-- SECTION 3: Migration 003 — Create Customer Predictions Table
-- ==============================================================================
CREATE TABLE IF NOT EXISTS customer_predictions (
    prediction_id VARCHAR(50) PRIMARY KEY,
    customer_id VARCHAR(50) NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    churn_probability NUMERIC(6, 4) NOT NULL CHECK (churn_probability >= 0.0 AND churn_probability <= 1.0),
    retention_probability NUMERIC(6, 4) NOT NULL CHECK (retention_probability >= 0.0 AND retention_probability <= 1.0),
    predicted_churn INTEGER NOT NULL CHECK (predicted_churn IN (0, 1)),
    decision_threshold NUMERIC(4, 2) NOT NULL DEFAULT 0.50 CHECK (decision_threshold = 0.50),
    risk_tier VARCHAR(20) NOT NULL CHECK (risk_tier IN ('HIGH', 'MODERATE', 'LOW')),
    model_name VARCHAR(100) NOT NULL DEFAULT 'RandomForestClassifier_ConfigD',
    model_version VARCHAR(50) NOT NULL DEFAULT '1.0.0',
    model_hash VARCHAR(64) NOT NULL DEFAULT '24F1F0E33C75B5590906369960DB6E5951EC95DF9AE40384DA60082B3438F301',
    prediction_timestamp TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_prediction_prob_sum CHECK (ABS(churn_probability + retention_probability - 1.0) <= 0.001)
);

COMMENT ON TABLE customer_predictions IS 'Auditable log of customer churn predictions generated by the locked Random Forest pipeline.';
COMMENT ON COLUMN customer_predictions.decision_threshold IS 'Locked decision boundary tau = 0.50 permanently enforced.';
COMMENT ON COLUMN customer_predictions.model_hash IS 'Cryptographic SHA-256 hash verifying the immutable production model binary.';

INSERT INTO schema_migrations (version, name)
VALUES ('003_create_customer_predictions', 'Creates the customer_predictions table to store ML inference history')
ON CONFLICT (version) DO NOTHING;


-- ==============================================================================
-- SECTION 4: Migration 004 — Create Customer Segments Table
-- ==============================================================================
CREATE TABLE IF NOT EXISTS customer_segments (
    segment_record_id VARCHAR(50) PRIMARY KEY,
    customer_id VARCHAR(50) NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    cluster_id INTEGER NOT NULL CHECK (cluster_id IN (0, 1, 2, 3, 4)),
    segment_name VARCHAR(100) NOT NULL CHECK (segment_name IN (
        'Champions & High-Value Loyalists',
        'At-Risk / Lapsed Low-Value Customers',
        'Zero Delivered-Purchase Customers',
        'Steady Core Repeaters',
        'Recent Low-Ticket / New Promising Customers'
    )),
    recency_delivered_days NUMERIC(10, 2) NOT NULL CHECK (recency_delivered_days >= 0.0),
    hist_delivered_order_count INTEGER NOT NULL CHECK (hist_delivered_order_count >= 0),
    hist_delivered_order_value_inr NUMERIC(12, 2) NOT NULL CHECK (hist_delivered_order_value_inr >= 0.0),
    segmentation_model VARCHAR(100) NOT NULL DEFAULT 'KMeans_RFM_K5',
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Partial unique index ensuring exactly one active segment per customer while retaining history
CREATE UNIQUE INDEX IF NOT EXISTS uq_current_customer_segment
    ON customer_segments (customer_id)
    WHERE is_current = TRUE;

COMMENT ON TABLE customer_segments IS 'RFM customer segmentation assignments using pre-fitted K-Means (K=5).';
COMMENT ON COLUMN customer_segments.recency_delivered_days IS 'Days since last delivered purchase (1117.0 for zero-delivered cohort).';

INSERT INTO schema_migrations (version, name)
VALUES ('004_create_customer_segments', 'Creates the customer_segments table to store RFM K-Means clustering assignments')
ON CONFLICT (version) DO NOTHING;


